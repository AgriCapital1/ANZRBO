import { supabase } from "@/integrations/supabase/client";

export type MemberDraft = {
  id: string;
  createdAt: string;
  member: {
    nom: string; prenoms: string; telephone: string; contact2: string | null;
    quartier: string | null; ville: string; date_naissance: string;
    lieu_naissance: string; date_inscription: string; statut: "en_attente";
  };
  payment: { methode: string; reference_externe: string | null; montant: number } | null;
};

const KEY = "anzrbo:pending-member-writes:v1";

function readQueue(): MemberDraft[] {
  if (typeof window === "undefined") return [];
  try {
    const parsed: unknown = JSON.parse(window.localStorage.getItem(KEY) ?? "[]");
    return Array.isArray(parsed) ? parsed as MemberDraft[] : [];
  } catch { return []; }
}
function writeQueue(queue: MemberDraft[]) {
  if (typeof window !== "undefined") window.localStorage.setItem(KEY, JSON.stringify(queue));
}
export function queueMemberDraft(draft: MemberDraft) {
  const queue = readQueue();
  if (!queue.some((item) => item.id === draft.id)) queue.push(draft);
  writeQueue(queue);
}
export function pendingMemberDraftCount() { return readQueue().length; }

/**
 * Local storage is an offline outbox only, never a member directory/cache.
 * Each draft is removed only after the authoritative database insert succeeds.
 */
export async function syncPendingMemberDrafts() {
  if (typeof window === "undefined" || !navigator.onLine) return { synced: 0, pending: readQueue().length };
  let queue = readQueue();
  let synced = 0;
  for (const draft of queue) {
    const { data: existing, error: lookupError } = await supabase
      .from("members")
      .select("id")
      .eq("numero_membre", draft.id)
      .maybeSingle();
    // A draft ID is a local idempotency key, not a member number. The actual
    // member number is generated by the database; use the draft ID in notes
    // to make retries safe after an interrupted response.
    if (lookupError) break;
    if (existing) {
      queue = queue.filter((item) => item.id !== draft.id);
      writeQueue(queue);
      synced++;
      continue;
    }
    const { error } = await supabase.from("members").insert({
      ...draft.member,
      notes: `offline_draft_id:${draft.id}`,
    });
    if (error) {
      // Keep the draft for a later retry. Do not pretend it was saved.
      break;
    }
    queue = queue.filter((item) => item.id !== draft.id);
    writeQueue(queue);
    synced++;
  }
  return { synced, pending: queue.length };
}
